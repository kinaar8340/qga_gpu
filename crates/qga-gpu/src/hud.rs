//! 2D HUD primitives. Scene-specific overlays live in the caller.

use crate::types::HudVert;

pub fn hud_quad(v: &mut Vec<HudVert>, x0: f32, y0: f32, x1: f32, y1: f32, c: [f32; 4]) {
    quad(v, x0, y0, x1, y1, c);
}

pub fn hud_stroke(v: &mut Vec<HudVert>, x0: f32, y0: f32, x1: f32, y1: f32, w: f32, c: [f32; 4]) {
    stroke(v, x0, y0, x1, y1, w, c);
}

pub fn hud_text(v: &mut Vec<HudVert>, x: f32, y: f32, s: f32, msg: &str, c: [f32; 4]) {
    text(v, x, y, s, msg, c);
}

fn quad(v: &mut Vec<HudVert>, x0: f32, y0: f32, x1: f32, y1: f32, c: [f32; 4]) {
    let p = [[x0, y0], [x1, y0], [x1, y1], [x0, y0], [x1, y1], [x0, y1]];
    for q in p {
        v.push(HudVert::new(q, c));
    }
}

fn stroke(v: &mut Vec<HudVert>, x0: f32, y0: f32, x1: f32, y1: f32, w: f32, c: [f32; 4]) {
    let dx = x1 - x0;
    let dy = y1 - y0;
    let len = (dx * dx + dy * dy).sqrt().max(1e-6);
    let nx = -dy / len * w * 0.5;
    let ny = dx / len * w * 0.5;
    let a = [x0 - nx, y0 - ny];
    let b = [x1 - nx, y1 - ny];
    let d = [x1 + nx, y1 + ny];
    let e = [x0 + nx, y0 + ny];
    for q in [a, b, d, a, d, e] {
        v.push(HudVert::new(q, c));
    }
}

fn text(v: &mut Vec<HudVert>, mut x: f32, y: f32, s: f32, msg: &str, c: [f32; 4]) {
    let cw = s * 1.15;
    for ch_c in msg.chars() {
        if let Some(rows) = glyph(ch_c) {
            for (row, bits) in rows.iter().enumerate() {
                for col in 0..5 {
                    if bits & (1 << (4 - col)) != 0 {
                        let px = x + col as f32 * s * 0.22;
                        let py = y - row as f32 * s * 0.26;
                        quad(v, px, py, px + s * 0.20, py + s * 0.24, c);
                    }
                }
            }
        }
        x += cw;
    }
}

/// 5×7 bitmap, MSB = left pixel.
